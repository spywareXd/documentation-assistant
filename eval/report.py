"""Regenerate RESULTS.md from results/*.json. Every number in RESULTS.md comes from these files.

    python -m eval.report
"""
from __future__ import annotations

import json
from pathlib import Path

from docrag.config import ROOT

RESULTS = ROOT / "results"
OUT = ROOT / "RESULTS.md"

# experiment id -> (title, ordered run names, columns)
RETRIEVAL_COLS = [("recall@1", "R@1"), ("recall@5", "R@5"), ("recall@10", "R@10"), ("mrr", "MRR"),
                  ("ndcg@10", "nDCG@10")]
TABLES = {
    "E0": ("Baseline: original design on the new corpus", "e0_"),
    "E1": ("Chunking strategies (hybrid + rerank held fixed)", "e1_"),
    "E2": ("Retrieval methods", "e2_"),
    "E3": ("Dynamic k", "e3_"),
    "E4": ("Query transformations", "e4_"),
    "E5": ("End-to-end: single-shot vs corrective agentic RAG", "e5_"),
}


def _fmt(v, pct=False) -> str:
    if v is None:
        return "–"
    if isinstance(v, float):
        return f"{v * 100:.1f}" if pct else f"{v:.3f}"
    return str(v)


def _load(split: str) -> dict[str, dict]:
    runs = {}
    for f in sorted(RESULTS.glob(f"*__{split}.json")):
        r = json.loads(f.read_text())
        runs[r["name"]] = r
    return runs


def _table(runs: list[dict]) -> str:
    gen = any("generation" in r["metrics"] for r in runs)
    head = ["run", *[c for _, c in RETRIEVAL_COLS], "R@5 95% CI", "ctx prec", "k", "p50 ms", "p95 ms"]
    if gen:
        head += ["correct", "faithful", "cite prec", "refuse (unans.)", "false refuse"]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for r in runs:
        m = r["metrics"]["retrieval"]
        ci = r["metrics"]["retrieval_ci95"].get("recall@5")
        lat = r["metrics"]["latency_ms"]["end_to_end"]
        row = [r["name"], *[_fmt(m.get(k)) for k, _ in RETRIEVAL_COLS],
               f"{ci[0]:.3f}–{ci[1]:.3f}" if ci else "–", _fmt(m.get("context_precision")),
               _fmt(m.get("k_selected")), _fmt(lat.get("p50")), _fmt(lat.get("p95"))]
        if gen:
            g = r["metrics"].get("generation", {})
            row += [_fmt(g.get(k)) for k in ("correctness", "faithfulness", "citation_precision",
                                              "unanswerable_refusal_rate", "false_refusal_rate")]
        lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines)


def main() -> None:
    out = ["# Results", "",
           "Generated by `python -m eval.report` from `results/*.json`. Do not edit by hand.", ""]
    for split in ("test", "dev"):
        runs = _load(split)
        if not runs:
            continue
        any_run = next(iter(runs.values()))
        env = any_run["environment"]
        out += [f"## Split: {split}", "",
                f"Questions: {any_run['metrics']['n_questions']} ({any_run['metrics']['n_answerable']} answerable). "
                f"Hardware: {env.get('gpu') or 'CPU'}. Corpus: {env.get('corpus', {}).get('documents', '?')} pages. "
                f"Latest run: {max(r['environment']['date_utc'] for r in runs.values())}.", ""]
        for eid, (title, prefix) in TABLES.items():
            group = [r for name, r in runs.items() if name.startswith(prefix)]
            if group:
                out += [f"### {eid}. {title}", "", _table(group), ""]
    out += ["## Metric definitions", "",
            "- **R@k** (recall@k): share of a question's gold evidence passages covered by the top-k chunks.",
            "- **MRR**: 1 / rank of the first chunk covering any gold evidence.",
            "- **nDCG@10**: rank-discounted gain, counting a chunk only if it covers new evidence.",
            "- **ctx prec**: share of chunks sent to the LLM that cover gold evidence; **k**: average chunks sent.",
            "- **correct / faithful**: LLM judge (see `eval/judge.py`); judge agreement with a human is in `results/spotcheck.json`.",
            "- **cite prec**: share of cited chunks that cover gold evidence.",
            "- Latency is wall-clock per question after warm-up, including LLM calls when present.", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"-> {OUT}")


if __name__ == "__main__":
    main()
